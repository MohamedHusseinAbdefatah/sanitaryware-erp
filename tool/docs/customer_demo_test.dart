            '5. قرارات مطلوبة من العميل والمحاسب',
            '6. التحضير قبل العرض',
          ])
            pw.Text(t),
        ],
      ),
    ));

    final body = <pw.Widget>[
      heading('1. ما هو البرنامج'),
      for (final p in _overview) bullet(p),
      pw.SizedBox(height: 10),
