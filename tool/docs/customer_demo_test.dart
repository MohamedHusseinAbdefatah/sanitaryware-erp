          pw.SizedBox(height: 24),
          pw.Image(shot('02_dashboard'), width: 440),
          pw.SizedBox(height: 24),
          pw.Text('المحتويات', style: bold),
          for (final t in [
            '1. ما هو البرنامج',
            '2. ما يعمل الآن',
            '3. سيناريوهات العرض خطوة بخطوة (${_scenarios.length} سيناريو)',
