          child: pw.Text(text, style: pw.TextStyle(fontSize: 17, fontWeight: pw.FontWeight.bold, color: PdfColors.white)),
        );
    pw.Widget numbered(int n, String text) => pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 3),
          child: pw.Row(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.SizedBox(width: 20, child: pw.Text('$n.', style: bold)),
              pw.Expanded(child: pw.Text(text)),
            ],
          ),
        );
    pw.Widget bullet(String text, {PdfColor color = teal}) => pw.Padding(
          padding: const pw.EdgeInsets.only(bottom: 3),
          child: pw.Row(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [pw.Text('•  ', style: pw.TextStyle(color: color)), pw.Expanded(child: pw.Text(text))],
          ),
        );

